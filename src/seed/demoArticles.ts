/** מוחק את שני מאמרי הדוגמה הישנים ("[דוגמה]"), ויוצר את המאמרים שעוד לא קיימים */
export async function seedDemoArticles(db: DbClient, staffIds: number[]): Promise<void> {
  const [nurse, social, therapist] = staffIds;
  if (nurse === undefined || social === undefined || therapist === undefined) return;
  const authorIds: Record<Author, number> = { nurse, social, therapist };

  await db.article.deleteMany({
    where: { title: { in: ["[דוגמה] מדריך קצר להאכלת פגים", "[דוגמה] מאמר חיצוני"] } },
  });

  const all = [...STAFF_ARTICLES, ...EXTERNAL_ARTICLES];
  const existing = await db.article.findMany({
    where: { title: { in: all.map((article) => article.title) } },
    select: { title: true },
  });
  const existingTitles = new Set(existing.map((article) => article.title));

  // תאריכי הוספה שונים, כדי שהרשימה תיראה כמו אתר שמתעדכן לאורך זמן
  const now = Date.now();
  const DAY = 24 * 60 * 60 * 1000;
  let index = 0;
  for (const article of all) {
    index += 1;
    if (existingTitles.has(article.title)) continue;
    const createdAt = new Date(now - index * 2 * DAY);
    const { author, ...fields } = article;
    await db.article.create({
      data: { ...fields, authorId: authorIds[author], createdAt, updatedAt: createdAt },
    });
  }
}
